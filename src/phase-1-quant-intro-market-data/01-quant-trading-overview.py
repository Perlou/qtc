# ==================== 第五部分：第一个量化策略 ====================


def first_strategy():
    """用沪深 300 跑一个最简单的均线择时策略"""
    print("\n" + "=" * 60)
    print("第五部分：第一个量化策略 —— 沪深 300 均线择时")
    print("=" * 60)

    # 1. 数据：沪深 300 指数日线
    df = get_index_daily("000300", "20180101", "20241231")
    close = df["close"]
    print(f"\n📊 数据：沪深 300，{close.index[0].date()} ~ {close.index[-1].date()}，共 {len(close)} 个交易日")

    # 2. 信号：收盘价在 60 日均线之上 → 看多(1)，否则空仓(0)
    ma = close.rolling(60).mean()
    signal = (close > ma).astype(int)

    # 3. 持仓：今天收盘才知道信号，最早明天才能按信号持仓 → shift(1)
    #    忘记 shift 是新手最常见的"未来函数"错误，回测会好得离谱
    position = signal.shift(1).fillna(0)

    # 4. 收益：持仓 × 指数日收益（这里暂不考虑交易成本）
    daily_ret = close.pct_change().fillna(0)
    strategy_ret = position * daily_ret

    # 5. 净值：日收益连乘
    nav = pd.DataFrame(
        {"买入持有": (1 + daily_ret).cumprod(), "均线择时": (1 + strategy_ret).cumprod()}
    )
    cheat_nav = (1 + signal * daily_ret).cumprod()  # 错误示范：没有 shift

    def summary(ret: pd.Series) -> dict:
        nav_ = (1 + ret).cumprod()
        years = len(ret) / 252
        return {
            "总收益": f"{nav_.iloc[-1] - 1:+.2%}",
            "年化收益": f"{nav_.iloc[-1] ** (1 / years) - 1:+.2%}",
            "年化波动": f"{ret.std() * np.sqrt(252):.2%}",
            "最大回撤": f"{(nav_ / nav_.cummax() - 1).min():.2%}",
        }

    result = pd.DataFrame(
        {
            "买入持有": summary(daily_ret),
            "均线择时": summary(strategy_ret),
            "❌ 未 shift（未来函数）": summary(signal * daily_ret),
        }
    )
    print("\n📈 回测结果（未计交易成本）：")
    print(result.to_string())

    trades = int(position.diff().abs().sum())
    print(f"\n🔄 换仓次数：{trades}（每次约 0.1%~0.2% 成本，{trades} 次合计不可忽略）")
    print(f"📉 持仓天数占比：{position.mean():.1%}")
    print(f"💰 期末净值：买入持有 {nav['买入持有'].iloc[-1]:.3f}，均线择时 {nav['均线择时'].iloc[-1]:.3f}，"
          f"未 shift {cheat_nav.iloc[-1]:.3f}")

    print("""
    💡 观察要点：
       1. 均线择时主要价值在于"降低回撤"，而不一定提高收益
       2. 未 shift 的版本收益虚高 —— 它在用"今天收盘价"决定"今天的持仓"
       3. 这段代码只有 4 步：数据 → 信号 → 持仓 → 净值，这就是所有回测的骨架
          Phase 4 会在此基础上加入交易成本、A 股约束和严谨的绩效评估
    """)


